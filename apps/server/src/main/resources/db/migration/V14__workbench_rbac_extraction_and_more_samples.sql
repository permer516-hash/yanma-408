CREATE TABLE material_authorization_attachments (
    id UUID PRIMARY KEY,
    material_asset_id UUID NOT NULL REFERENCES material_assets(id) ON DELETE CASCADE,
    audit_id UUID REFERENCES material_copyright_audits(id) ON DELETE SET NULL,
    bucket VARCHAR(128) NOT NULL,
    object_key VARCHAR(512) NOT NULL,
    original_file_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(128) NOT NULL,
    size_bytes BIGINT NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    uploaded_by UUID REFERENCES app_users(id) ON DELETE SET NULL,
    notes TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_material_authorization_attachments_size
        CHECK (size_bytes > 0),
    CONSTRAINT uq_material_authorization_attachment_object
        UNIQUE (bucket, object_key)
);

CREATE TABLE material_extraction_candidates (
    id UUID PRIMARY KEY,
    material_asset_id UUID NOT NULL REFERENCES material_assets(id) ON DELETE CASCADE,
    page_number INTEGER NOT NULL,
    extraction_method VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    raw_text TEXT,
    suggested_stem TEXT,
    confidence NUMERIC(5, 2),
    created_by UUID REFERENCES app_users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_material_extraction_candidates_method
        CHECK (extraction_method IN ('PDF_TEXT', 'OCR')),
    CONSTRAINT chk_material_extraction_candidates_status
        CHECK (status IN ('EXTRACTED', 'OCR_REQUIRED', 'EMPTY', 'FAILED')),
    CONSTRAINT chk_material_extraction_candidates_page
        CHECK (page_number > 0)
);

CREATE TABLE question_draft_references (
    id UUID PRIMARY KEY,
    draft_id UUID NOT NULL REFERENCES question_drafts(id) ON DELETE CASCADE,
    material_asset_id UUID REFERENCES material_assets(id) ON DELETE SET NULL,
    extraction_candidate_id UUID REFERENCES material_extraction_candidates(id) ON DELETE SET NULL,
    page_number INTEGER,
    quote TEXT,
    reference_note TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_question_draft_references_page
        CHECK (page_number IS NULL OR page_number > 0)
);

